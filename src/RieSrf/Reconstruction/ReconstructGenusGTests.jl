################################################################################
#
#  The eta test at a hyperelliptic curve
#
#  The reconstruction uses eta = (0..0; 1 0..0) in the basis of the (Siegel
#  reduced) period matrix. Transforming tau by gamma in Sp_2g(Z) (without
#  reducing again) moves eta to another 2-torsion point of the same curve.
#  For a generic curve every eta gives the same 3 quadrics (the canonical
#  ideal). For a hyperelliptic curve the quadrics containing the canonical
#  image (a rational normal curve) form a space of dimension 6; if the Prym
#  construction picks 3 of them depending on eta, the quadrics of several
#  eta span more than 3 (up to 6) dimensions. All quadrics are expressed in
#  the coordinates of the differentials of the curve (rows of the big period
#  matrix), so they are comparable across eta.
#
################################################################################

@doc raw"""
    eta_quadric_span(; curve = nothing, etas = 6, prec = 600, seed = 1, sign_data = nothing,
                     verbose = true) -> NamedTuple

For a hyperelliptic curve of genus 5 (hyperelliptic_test_curve, or `curve`):
the quadrics of the reconstruction (reconstruct_quadrics_from_thetas, not
strict) for `etas` different 2-torsion points eta (the reduced period matrix
transformed by products of random integral transvections, the first one the
identity), in the coordinates of the differentials of the curve. Prym
signs that Riemann's relations leave free (products, hyperelliptic curves:
sign_completions) are enumerated (at most 2^max_free); the completions for
which the Fay relations of the Prym hold are kept (all their quadrics enter
the span). Prints per
eta the number of quadrics and the singular values of the relation matrix,
and the dimension of the span of the quadrics of the first k eta for
k = 1, 2, ... (3 throughout: the Prym picks an eta-independent net; growing
to 6: it filters the Petri quadrics depending on eta).
"""
function eta_quadric_span(; curve = nothing, etas::Int = 6, prec::Int = 600, seed::Int = 1, sign_data = nothing,
                          max_free::Int = 10, verbose::Bool = true)
  LA = RSR.LinearAlgebra
  Random.seed!(seed)
  g = 5
  F = curve === nothing ? hyperelliptic_test_curve(g) : curve
  verbose && println("curve ", F)
  RS = RSR.riemann_surface(F, prec)
  Pi = RSR.big_period_matrix(RS)
  CC = base_ring(Pi)
  tau = RSR._solve_precond(Pi[:, 1:g], Pi[:, g+1:2*g])
  tau = (tau + transpose(tau)) * inv(CC(2))
  T, tau_red = Hecke.siegel_reduction(tau)
  data4 = _loaded_sign_data(sign_data, g - 1)
  e2 = RSR._exponent_vectors(g, 2)
  function random_gamma()
    M = identity_matrix(ZZ, 2 * g)
    for _ in 1:4
      v = [rand(0:1) for _ in 1:2*g]
      iszero(v) && continue
      M = M * matrix(ZZ, _integral_transvection(v, g))
    end
    return M
  end
  gammas = [identity_matrix(ZZ, 2 * g); [random_gamma() for _ in 2:etas]]
  per_eta = NamedTuple[]
  coefficient_rows = Vector{Vector{ComplexF64}}()
  spans = Int[]
  for (k, gamma) in enumerate(gammas)
    clock = time()
    record = try
      tk = isone(gamma) ? tau_red : Hecke.siegel_transform(gamma, tau_red)
      thetas = Hecke.thetas([zero(base_ring(tk)) for _ in 1:g], tk)
      tkprec = precision(base_ring(tk))
      # the gradients of the curve (independent of the Prym signs), directly
      # from the theta jets at tk: at a hyperelliptic curve the Fay relations
      # of the curve do not have the generic rank, so the Fay kernel cannot
      # be used; in these coordinates B = 1
      jets = Hecke.theta_jets([zero(base_ring(tk)) for _ in 1:g], tk, 1)
      jet(c) = haskey(jets, Tuple(c)) ? jets[Tuple(c)] : jets[collect(c)]
      unit(i) = ntuple(l -> Int(l == i), g)
      odds = odd_theta_characteristics(g)
      K = matrix(base_ring(tk), length(odds), g, [jet(c)[unit(i)] for c in odds for i in 1:g])
      q_B = -Inf
      data = (tau = tk, transform = gamma * T, coordinates = identity_matrix(base_ring(tk), g))
      L = _coordinates_from_differentials(change_base_ring(base_ring(tk), Pi), data)
      # the Prym: Schottky-Jung, signs as far as Riemann's relations determine
      # them; the free signs enumerated, kept if the Fay relations of the
      # Prym hold
      sc = sign_completions(prym_thetas(g, thetas), g - 1, data4)
      @req sc.free <= max_free "$(sc.free) Prym signs not determined (more than max_free = $max_free)."
      nets = Vector{Vector{Vector{ComplexF64}}}()
      residuals = Float64[]
      for bits in Iterators.product(ntuple(_ -> (false, true), sc.free)...)
        tp = sc.completion(collect(Bool, bits))
        Kp, q_Kp = try
          odd_theta_gradient_kernel(g - 1, tp)
        catch
          continue
        end
        push!(residuals, q_Kp)
        q_Kp < -tkprec / 4 || continue
        quadrics, _ = _quadrics_from_gradients(g, K, Kp; strict = false)
        isempty(quadrics) && continue
        ys = gens(parent(quadrics[1]))
        xy = [sum(L[i, j] * ys[j] for j in 1:g) for i in 1:g]
        Qy = [evaluate(q, xy) for q in quadrics]
        rows = [[RSR._c64(coeff(q, e)) for e in e2] for q in Qy]
        push!(nets, [v ./ LA.norm(v) for v in rows])
      end
      @req !isempty(nets) "no sign completion satisfies the Prym Fay relations (residuals 2^$(round.(sort(residuals)[1:min(3, end)], digits = 1)))."
      (k = k, status = :ok, quadrics = length(nets[1]), rows = reduce(vcat, nets), nets = length(nets),
       free_signs = sc.free, coordinates_log2 = q_B, sign_data_sufficed = sc.free == 0)
    catch err
      err isa InterruptException && rethrow()
      (k = k, status = :error, error = first(sprint(showerror, err), 200))
    end
    push!(per_eta, record)
    if record.status === :ok
      append!(coefficient_rows, record.rows)
      A = permutedims(reduce(hcat, coefficient_rows))
      s = LA.svdvals(A)
      push!(spans, count(>(1e-8 * s[1]), s))
      verbose && println("eta $k: $(record.quadrics) quadrics (gradient coordinates 2^$(round(record.coordinates_log2, digits = 1)), ",
                         "$(record.free_signs) free Prym signs, $(record.nets) completions with valid Prym Fay relations); ",
                         "span of the quadrics so far: ",
                         spans[end], " (singular values 10^", round.(log10.(max.(s ./ s[1], 1e-300)), digits = 1), ") [",
                         round(time() - clock, digits = 1), " s]")
    else
      verbose && println("eta $k: error ", record.error, " [", round(time() - clock, digits = 1), " s]")
    end
  end
  return (curve = F, per_eta = per_eta, spans = spans)
end
