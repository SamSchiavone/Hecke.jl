    j = first(block)
    rows = NamedTuple[]
    for x in oks
      g = nrows(x.tau)
      perm = collect(1:g)
      perm[1], perm[j] = j, 1
      t = matrix(base_ring(x.tau), g, g, [x.tau[perm[a], perm[b]] for a in 1:g for b in 1:g])
