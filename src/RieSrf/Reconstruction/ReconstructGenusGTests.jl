  end
  return tables
end

################################################################################
#
#  A family of genus 5 curves tending to a hyperelliptic curve
#
#  Plane curves F_t of degree 7 with an ordinary 4-fold point at the origin
#  and nodes at t p_1, ..., t p_4: genus 15 - 6 - 4 = 5, trigonal (projection
#  from the 4-fold point). The limit must be an ordinary 5-fold point (delta
#  10, genus 5, hyperelliptic: projection from it) with delta constant along
#  the family. Model: five lines, four through the origin and the fifth
#  l = t; the nodes are where the fifth meets the four. So the p_i lie on the
#  line l = 1 and in the tangent cone of the 4-fold point (F_4(p_i) = 0);
#  the nodes are at t p_i + t^2 q_i (q_i random): on the line exactly, the
#  line would be a component (4 nodes give intersection 8 > 7).
#
#  EXPERIMENTAL, does not work yet: with random q_i the delta-constant
#  direction is not in the linear system (checked in exact arithmetic: the
#  normalized member has F_4 ~ t^2, F_5 ~ t, F_6, F_7 ~ 1, so the limit has a
#  6-fold point and genus 0; forcing F_5 ~ 1 makes F_6, F_7 ~ 1/t). The node
#  positions of a genuine delta-constant family are determined by the higher
#  order terms (and are in general not rational), so they cannot be chosen
#  freely.
#  (Nodes at t p_i with p_i in general position force F_4 and F_5 to 0: a
#  6-fold point in the limit, genus 0.) F_t is the member of the linear system fixed by random
#  normalizations, a rational function of t (solved over QQ(t)), scaled so
#  that F_0 is its value at t = 0.
#
################################################################################

@doc raw"""
    hyperelliptic_degeneration_family(; coefficients = -3:3, max_tries = 20) -> NamedTuple

A family F_t (see above) with F_t of genus 5 for t != 0 and F_0 of genus 5
with a 5-fold point at the origin (hyperelliptic), checked modulo primes.
Returns (family (t -> F_t for t in QQ), F0, nodes (the p_i), polynomial (the
family in QQ[t][x, y])).
"""
function hyperelliptic_degeneration_family(; coefficients = -3:3, max_tries::Int = 20)
  Qt, T = polynomial_ring(QQ, :t; cached = false)
  K = fraction_field(Qt)
  R, (x, y) = polynomial_ring(QQ, [:x, :y]; cached = false)
  monomials = [(a, b) for a in 0:7 for b in 0:7-a if a + b >= 4]       # the 4-fold point at the origin
  n = length(monomials)                                                 # 26
  function genus_mod_p(F)
    p = next_prime(2^20)
    for _ in 1:20
      p = next_prime(p + 1)
      gp = try RSR._genus_mod_p(F, p) catch; nothing end
      gp === nothing || return gp
    end
    return nothing
  end
  reasons = Dict{String, Int}()
  reject(r) = (reasons[r] = get(reasons, r, 0) + 1; nothing)
  for _ in 1:max_tries
    # four points in distinct directions on the line l = 1 (l = l1 x + l2 y)
    l1, l2 = QQ(rand(1:3)), QQ(rand(-3:3))
    nodes = Tuple{QQFieldElem, QQFieldElem}[]
    while length(nodes) < 4
      d = (QQ(rand(-3:3)), QQ(rand(-3:3)))
      s = l1 * d[1] + l2 * d[2]
      iszero(s) && continue
      p = (d[1] // s, d[2] // s)
      any(q -> p[1] * q[2] == p[2] * q[1], nodes) && continue
      push!(nodes, p)
    end
    rows = Vector{Any}[]
    # the tangent cone of the 4-fold point through the nodes: F_4(p_i) = 0
    for (p1, p2) in nodes
      push!(rows, [a + b == 4 ? K(p1^a * p2^b) : K(0) for (a, b) in monomials])
    end
    # the nodes at t p_i + t^2 q_i: exactly collinear nodes would put the line
    # l = t into the curve (4 nodes on a line: intersection 8 > 7)
    bends = [(QQ(rand(-3:3)), QQ(rand(-3:3))) for _ in 1:4]
    for ((p1, p2), (q1, q2)) in zip(nodes, bends)
      u, v = T * p1 + T^2 * q1, T * p2 + T^2 * q2
      push!(rows, [K(u^a * v^b) for (a, b) in monomials])                              # F
      push!(rows, [a == 0 ? K(0) : K(a * u^(a - 1) * v^b) for (a, b) in monomials])     # F_x
      push!(rows, [b == 0 ? K(0) : K(b * u^a * v^(b - 1)) for (a, b) in monomials])     # F_y
    end
    for _ in 1:n - 16
      push!(rows, [K(rand(coefficients)) for _ in 1:n])
    end
    M = matrix(K, n, n, reduce(vcat, rows))
    rhs = matrix(K, n, 1, [i == n ? K(1) : K(0) for i in 1:n])
    c = try
      solve(M, rhs; side = :right)
    catch
      reject("singular system"); continue
    end
    # clear denominators and the common power of t
    d = reduce(lcm, [denominator(c[i, 1]) for i in 1:n])
    polys = [numerator(c[i, 1] * d) for i in 1:n]
    trailing(p) = iszero(p) ? typemax(Int) : findfirst(i -> !iszero(coeff(p, i)), 0:degree(p)) - 1
    v = minimum(trailing, polys)
    polys = [iszero(p) ? p : divexact(p, T^v) for p in polys]
    family(t) = sum(QQ(evaluate(polys[l], t)) * x^a * y^b for (l, (a, b)) in enumerate(monomials))
    F0 = family(QQ(0))
    F1 = family(QQ(1, 7))
    (total_degree(F1) == 7 && total_degree(F0) == 7) || (reject("degree"); continue)
    # the limit: no terms of degree 4 (a 5-fold point)
    all(t -> total_degree(t) >= 5, terms(F0)) || (reject("no 5-fold point in the limit"); continue)
    gt = genus_mod_p(F1)
    gt == 5 || (reject("genus of F_t: $gt"); continue)
    g0 = genus_mod_p(F0)
    g0 == 5 || (reject("genus of F_0: $g0"); continue)
    return (family = family, F0 = F0, nodes = nodes, bends = bends, polynomial = polys, monomials = monomials)
  end
  error("No suitable family found in $max_tries tries; rejected: $reasons.")
end

