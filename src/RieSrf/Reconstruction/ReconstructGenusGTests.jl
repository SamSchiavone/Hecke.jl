# The blocks of a period matrix near a product of Jacobians: the connected
# components of the graph on the coordinates with an edge where
# log2 |tau_ij| > threshold.
function _period_matrix_blocks(tau::AcbMatrix; threshold::Float64 = -8.0)
  g = nrows(tau)
  component = collect(1:g)
  find(i) = component[i] == i ? i : (component[i] = find(component[i]))
  for i in 1:g, j in i+1:g
    RSR._safe_log2(RSR._abs64(tau[i, j])) > threshold && (component[find(i)] = find(j))
  end
  roots = unique(find(i) for i in 1:g)
  return [[i for i in 1:g if find(i) == r] for r in roots]
end

@doc raw"""
    block_classifications(r; threshold = -8.0, sign_data = nothing) -> Vector

For the results r of approach_cusp_limit (period matrices near a product of
Jacobians): the classification depends on where eta = (0..0; 1 0..0), i.e.
the coordinate 1, lies relative to the blocks of the product (the Prym of
