# One line of evidence of classify_jacobian
function _evidence_line(c)
  e = c.evidence
  parts = String[]
  haskey(e, :schottky_jung_rank) && push!(parts, "Schottky-Jung rank $(e.schottky_jung_rank)/$(e.schottky_jung_needed)")
  haskey(e, :gradient_residual) && push!(parts, "Fay residual $(round(e.gradient_residual, digits = 1))")
  haskey(e, :prym_gradient_residual) && push!(parts, "Prym Fay residual $(e.prym_gradient_residual)")
  haskey(e, :squares_singular_values_log2) &&
    push!(parts, "smallest squares singular value 2^$(round(minimum(e.squares_singular_values_log2), digits = 1))")
  haskey(e, :quadric_count) && push!(parts, "quadrics $(e.quadric_count) (gap $(round(e.quadric_gap_bits, digits = 1)) bits)")
  haskey(e, :quadric_singular_values_log2) &&
    push!(parts, "relation matrix singular values (log2) $(round.(e.quadric_singular_values_log2[1:min(7, end)], digits = 1))")
  for key in (:schottky_jung_error, :gradient_kernel_error, :prym_gradient_kernel_error)
    haskey(e, key) && push!(parts, "$key: $(first(e[key], 120))")
  end
  return join(parts, "; ")
end

@doc raw"""
    hyperelliptic_test_curve(g; coefficients = -3:3) -> MPolyRingElem

y^2 - f(x) for a random squarefree f of degree 2g + 2 with coefficients in
`coefficients` (a hyperelliptic curve of genus g).
"""
function hyperelliptic_test_curve(g::Int; coefficients = -3:3)
  Qt, t = polynomial_ring(QQ, :t; cached = false)
  R, (x, y) = polynomial_ring(QQ, [:x, :y]; cached = false)
  while true
    f = sum(QQ(rand(coefficients)) * t^i for i in 0:2*g+2)
    degree(f) == 2*g + 2 && is_squarefree(f) || continue
    return y^2 - sum(coeff(f, i) * x^i for i in 0:2*g+2)
  end
end

@doc raw"""
    product_period_matrix(partition, prec; coefficients = -3:3, reduce = true, jacobians = true)
      -> AcbMatrix, Vector

The block diagonal period matrix of a product of Jacobians of dimensions
`partition` (e.g. [2, 3]), Siegel reduced if `reduce` (the reduction need
not keep the blocks): random_siegel_matrix for
dimensions 1, 2, 3 (a generic principally polarized abelian variety of
dimension at most 3 is a Jacobian), a random plane curve of genus 4
(the genus 4 tests' _random_g4_curve(:generic)) for 4, a random canonical
curve of genus 5 for 5; with `jacobians = false` random Siegel matrices
for all dimensions (generic, for dimensions 4 and 5 not Jacobians). Also
returns the curves (nothing for the random
matrices).
"""
function product_period_matrix(partition::Vector{Int}, prec::Int; coefficients = -3:3, reduce::Bool = true,
                               jacobians::Bool = true)
  @req all(h -> 1 <= h <= 5, partition) "The dimensions must be between 1 and 5."
  CC = AcbField(prec)
  g = sum(partition)
  T = zero_matrix(CC, g, g)
  curves = Any[]
  offset = 0
  for h in partition
    if h <= 3 || !jacobians
      tau = random_siegel_matrix(h, prec)
      push!(curves, nothing)
    elseif h == 4
      tau = nothing
      for _ in 1:20
        f = RSR._random_g4_curve(:generic; coeff_range = coefficients)
        RS = RSR.riemann_surface(f, prec; superelliptic = false, model = :original)
        t = _small_period_matrix(RSR.big_period_matrix(RS))
        nrows(t) == 4 || continue
        tau = t
        push!(curves, f)
        break
      end
      @req tau !== nothing "No curve of genus 4 found."
    else
      curve = canonical_test_curve_g5(; coefficients = coefficients)
      RS = riemann_surface_with_differentials(curve.plane, curve.numerators, prec)
      tau = _small_period_matrix(RSR.big_period_matrix(RS))
      push!(curves, curve.plane)
    end
    for i in 1:h, j in 1:h
      T[offset + i, offset + j] = CC(tau[i, j])
    end
    offset += h
  end
  return reduce ? Hecke.siegel_reduction(T)[2] : T, curves
end

# The values at points of the curve (random x-coordinates, a root y) of the
# normalized differentials (A^-1 omega for the big period matrix [A B]) of a
# plane curve with Riemann surface RS (model :original), up to the common
# factor dx: one vector per point.
function _normalized_differentials_at_points(RS, f::MPolyRingElem, count::Int)
  O = RSR.original_model(RS)
  factor_set, factor_matrix, _, _ = RSR.differential_form_data(O)
  Pi = RSR.big_period_matrix(RS)
  h = nrows(Pi)
  CC = base_ring(Pi)
  prec = precision(CC)
  Cy, _ = polynomial_ring(CC, :y; cached = false)
  # the factors may be defined over a number field (the field of the model):
  # embedded with the embedding of RS
  embedded_factors = [coefficient_ring(q) == QQ ? q : RSR._embed_mpoly(q, RSR.embedding(RS), prec) for q in factor_set]
  vectors = Vector{AcbFieldElem}[]
  while length(vectors) < count
    x0 = CC(QQ(rand(-100:100), 37), QQ(rand(-100:100), 41))
    coefficients_y = [zero(CC) for _ in 0:degree(f, 2)]
    for (c, e) in zip(Hecke.coefficients(f), Hecke.exponent_vectors(f))
      coefficients_y[e[2] + 1] += CC(c) * x0^e[1]
    end
    py = Cy(coefficients_y)
    rts = roots(py, target = prec, initial_prec = prec, max_prec = 8 * prec)
    isempty(rts) && continue
    y0 = rts[rand(1:length(rts))]
    point = [x0, y0]
    factor_values = [evaluate(embedded, point) for embedded in embedded_factors]
    any(contains_zero, factor_values) && continue
    values = [prod(factor_values[l]^factor_matrix[l, k] for l in 1:length(factor_set)) for k in 1:h]
    v = RSR._solve_precond(Pi[:, 1:h], matrix(CC, h, 1, values))
    push!(vectors, [v[i, 1] for i in 1:h])
  end
  return vectors
end

@doc raw"""
    compact_type_degeneration(partition, prec; coefficients = -3:3) -> NamedTuple

A chain of curves C_1 - C_2 - ... of genera `partition` (1 to 4) and the
first order degeneration of the Jacobians of its smoothings (Fay): the block
diagonal period matrix tau0 (Jacobian of the chain, not Siegel reduced) and
the direction D, symmetric with the blocks u_i v_{i+1}^T between consecutive
curves, u_i (v_{i+1}) the values of the normalized differentials of C_i
(C_{i+1}) at the points glued: tau0 + t D is the period matrix of a
smoothing up to O(t^2) (constants absorbed in t). Genus 1, 2: random Siegel
matrices (every direction is a point of the canonical image up to scale),
genus 3: a random plane quartic, genus 4: a random curve of bidegree (3, 3)
(_random_g4_curve). D is an AcbMatrix (at the precision prec), as the first
order needs D to more than the precision of t. Returns (tau0, direction,
curves).
"""
function compact_type_degeneration(partition::Vector{Int}, prec::Int; coefficients = -3:3)
  @req all(h -> 1 <= h <= 4, partition) "The genera must be between 1 and 4."
  CC = AcbField(prec)
  g = sum(partition)
  T = zero_matrix(CC, g, g)
  D = zero_matrix(CC, g, g)
  R, (x, y) = polynomial_ring(QQ, [:x, :y]; cached = false)
  curves = Any[]
  node_vectors = Vector{Vector{Vector{AcbFieldElem}}}()     # per curve: the points (left, right)
  for h in partition
    if h <= 2
      push!(curves, nothing)
      push!(node_vectors, [[CC(randn(), randn()) for _ in 1:h] for _ in 1:2])
      continue
    end
    found = false
    for _ in 1:20
      f = h == 3 ? sum(QQ(rand(coefficients)) * x^i * y^j for i in 0:4 for j in 0:4-i) :
                   RSR._random_g4_curve(:generic; coeff_range = coefficients)
      h == 3 && (total_degree(f) == 4 && length(RSR._newton_polygon_interior_points(f)) == 3 &&
                 RSR._baker_certified(f, 3) || continue)
      RS = RSR.riemann_surface(f, prec; superelliptic = false, model = :original)
      tau = _small_period_matrix(RSR.big_period_matrix(RS))
      nrows(tau) == h || continue
      push!(curves, f)
      push!(node_vectors, _normalized_differentials_at_points(RS, f, 2))
      found = true
      break
    end
    @req found "No curve of genus $h found."
    for i in 1:h, j in 1:h
      T[sum(partition[1:length(curves)-1]) + i, sum(partition[1:length(curves)-1]) + j] = CC(tau[i, j])
    end
  end
  # the blocks for h <= 2 (filled above only for the curves)
  offsets = cumsum([0; partition])
  for (c, h) in enumerate(partition)
    curves[c] === nothing || continue
    tau = random_siegel_matrix(h, prec)
    for i in 1:h, j in 1:h
      T[offsets[c] + i, offsets[c] + j] = CC(tau[i, j])
    end
  end
  for c in 1:length(partition)-1
    u, v = node_vectors[c][2], node_vectors[c + 1][1]
    for i in 1:partition[c], j in 1:partition[c + 1]
      D[offsets[c] + i, offsets[c + 1] + j] = D[offsets[c + 1] + j, offsets[c] + i] = u[i] * v[j]
    end
  end
  largest = maximum(RSR._abs64(D[i, j]) for i in 1:g for j in 1:g)
  D = D * inv(CC(largest))
  return (tau0 = T, direction = D, curves = curves)
end

@doc raw"""
    test_jacobian_classification(; jacobians = 3, generic_pryms = 3, quintics = 6, hyperelliptic = 2,
                                 products = 1, partitions = [[1, 4], [2, 3], [1, 1, 3], [1, 2, 2], [1, 1, 1, 2]],
                                 prec = 500,
                                 curve_sign_data_5, curve_sign_data_6, sign_data_4, fay_relations_6,
                                 certified_fixed_signs = false, gap_bits = nothing) -> Vector

A @testset for classify_jacobian on principally polarized abelian varieties
of dimension 5 whose type is known:

  - Jacobians of random genus 5 curves (canonical_test_curve_g5): :jacobian;
  - Pryms of random genus 6 curves (canonical_test_curve_g6; generic, not
    Jacobians): :not_jacobian;
  - Pryms of random smooth plane quintics (plane_quintic_test_curve): by
    Mumford a Jacobian if kappa + eta is even (kappa = O(1), the odd
    characteristic with vanishing gradient, found from the Fay kernel of the
    quintic), the intermediate Jacobian of a cubic threefold if it is odd:
    :jacobian resp. :not_jacobian;
  - Jacobians of random hyperelliptic curves of genus 5
    (hyperelliptic_test_curve) and `products` products of Jacobians for each
    partition of 5 in `partitions` (product_period_matrix): not tested
    (expected :unknown), only reported, to see what the reconstruction does.
    These have vanishing even theta constants, so their theta constants come
    from acb_theta_all and classify_jacobian runs with allow_vanishing.

The sign data: `curve_sign_data_5` (genus 5; the Jacobians and the signs of
the Pryms), `curve_sign_data_6` (genus 6, the theta constants of the genus
6 curves), `sign_data_4` (genus 4, for classify_jacobian); `fay_relations_6`
for the Fay kernel of the quintics. Prints per case the expected and the
found verdict with the evidence, and a summary. :inconclusive counts as a
failure, except for a period matrix known to less than half the precision
(reported as :inconclusive at stage :period_matrix and not tested: a
problem of the period matrix, not of the classification). Returns the
results.
"""
function test_jacobian_classification(; jacobians::Int = 3, generic_pryms::Int = 3, quintics::Int = 6,
                                      hyperelliptic::Int = 2, products::Int = 1,
                                      partitions = [[1, 4], [2, 3], [1, 1, 3], [1, 2, 2], [1, 1, 1, 2]],
                                      prec::Int = 500, coefficients = -3:3, curve_sign_data_5 = nothing,
                                      curve_sign_data_6 = nothing, sign_data_4 = nothing,
                                      fay_relations_6 = nothing, certified_fixed_signs::Bool = false,
                                      gap_bits = nothing)
  results = Any[]
  odds6 = odd_theta_characteristics(6)
  # the period matrix must be known to at least half the precision (some
  # curves give large radii): else :inconclusive, before the theta constants
  struct_precision(tau) = -maximum(RSR._log2_relative_radius(tau[i, j]) for i in 1:nrows(tau), j in 1:ncols(tau))
  function thetas_of(tau, data)
    bits = struct_precision(tau)
    bits < prec / 2 && throw(_ImpreciseTau(bits))
    return _theta_constants_by_method(Hecke.siegel_reduction(tau)[2], :riemann; curve_sign_data = data,
                                      certified_fixed_signs = certified_fixed_signs)
  end
  classify(thetas; allow_vanishing = false) = classify_jacobian(5, thetas; sign_data = sign_data_4, gap_bits = gap_bits,
                                                                allow_vanishing = allow_vanishing)
  # with vanishing even theta constants (hyperelliptic curves, products) the
  # signs by Riemann's relations are not available: acb_theta_all
  function thetas_flint(tau)
    bits = struct_precision(tau)
    bits < prec / 2 && throw(_ImpreciseTau(bits))
    t = Hecke.siegel_reduction(tau)[2]
    return Hecke.thetas([zero(base_ring(t)) for _ in 1:nrows(t)], t)
  end
  function record(kind, expected, compute)
    t = time()
    found = try
      compute()
    catch err
      err isa _ImpreciseTau ?
        (verdict = :inconclusive, stage = :period_matrix, error = "period matrix known to $(round(err.bits, digits = 1)) bits only", extra = "") :
        (verdict = :error, stage = :setup, error = sprint(showerror, err), extra = "")
    end
    line = hasproperty(found, :classification) ? _evidence_line(found.classification) : found.error
    extra = hasproperty(found, :extra) ? found.extra : ""
    println(rpad(kind, 34), " expected $(rpad(string(expected), 13)) found $(rpad(string(found.verdict), 13)) ",
            "($(found.stage), $(round(time() - t, digits = 1)) s) $extra")
    println("    ", line)
    push!(results, (kind = kind, expected = expected, verdict = found.verdict, stage = found.stage, result = found))
  end
  for i in 1:jacobians
    record("genus 5 Jacobian $i", :jacobian, () -> begin
      curve = canonical_test_curve_g5(; coefficients = coefficients)
      RS = riemann_surface_with_differentials(curve.plane, curve.numerators, prec)
      c = classify(thetas_of(_small_period_matrix(RSR.big_period_matrix(RS)), curve_sign_data_5))
      (verdict = c.verdict, stage = c.stage, classification = c, curve = curve)
    end)
  end
  for i in 1:generic_pryms
    record("Prym of a genus 6 curve $i", :not_jacobian, () -> begin
      curve = canonical_test_curve_g6(; coefficients = coefficients)
      RS = riemann_surface_with_differentials(curve.plane, curve.numerators, prec)
      thetas = thetas_of(_small_period_matrix(RSR.big_period_matrix(RS)), curve_sign_data_6)
      thetas_P, _ = _prym_theta_constants(6, thetas, curve_sign_data_5)
      c = classify(thetas_P)
      (verdict = c.verdict, stage = c.stage, classification = c, curve = curve)
    end)
  end
  for i in 1:quintics
    F = plane_quintic_test_curve(; coefficients = coefficients)
    RS = RSR.riemann_surface(F, prec; superelliptic = false, model = :original)
    local thetas, kappa, gap, expected
    try
      thetas = thetas_of(_small_period_matrix(RSR.big_period_matrix(RS)), curve_sign_data_6)
      K, _ = odd_theta_gradient_kernel(6, thetas; relations = fay_relations_6)
      norms = [maximum(RSR._abs64(K[r, c]) for c in 1:6) for r in 1:nrows(K)]
      order = sortperm(norms)
      kappa, gap = odds6[order[1]], RSR._safe_log2(norms[order[1]] / norms[order[2]])
      expected = isodd(kappa[1]) ? :jacobian : :not_jacobian
    catch err
      message = err isa _ImpreciseTau ? "period matrix known to $(round(err.bits, digits = 1)) bits only" :
                sprint(showerror, err)
      verdict = err isa _ImpreciseTau ? :inconclusive : :error
      println(rpad("Prym of a plane quintic $i", 34), " type unknown, $verdict: ", message)
      push!(results, (kind = "Prym of a plane quintic $i", expected = :unknown, verdict = verdict,
                      stage = :setup, result = (curve = F, error = err)))
      continue
    end
    record("Prym of a plane quintic $i", expected, () -> begin
      thetas_P, _ = _prym_theta_constants(6, thetas, curve_sign_data_5)
      c = classify(thetas_P)
      (verdict = c.verdict, stage = c.stage, classification = c, curve = F, kappa = kappa,
       extra = "kappa $(kappa) (gap 2^$(round(gap, digits = 1)))")
    end)
  end
  # hyperelliptic curves and products of Jacobians (vanishing theta
  # constants; what the reconstruction does is the question: expected
  # :unknown)
  for i in 1:hyperelliptic
    record("hyperelliptic curve of genus 5 $i", :unknown, () -> begin
      F = hyperelliptic_test_curve(5; coefficients = coefficients)
      RS = RSR.riemann_surface(F, prec)
      c = classify(thetas_flint(_small_period_matrix(RSR.big_period_matrix(RS))); allow_vanishing = true)
      (verdict = c.verdict, stage = c.stage, classification = c, curve = F,
       extra = "$(c.evidence.vanishing_theta_constants) vanishing theta constants")
    end)
  end
  for partition in partitions, i in 1:products
    record("product $(join(partition, "+")) $i", :unknown, () -> begin
      tau, curves = product_period_matrix(partition, prec; coefficients = coefficients)
      c = classify(thetas_flint(tau); allow_vanishing = true)
      (verdict = c.verdict, stage = c.stage, classification = c, curves = curves,
       extra = "$(c.evidence.vanishing_theta_constants) vanishing theta constants")
    end)
  end
  println()
  for kind in ("genus 5 Jacobian", "Prym of a genus 6 curve", "Prym of a plane quintic",
               "hyperelliptic curve", "product")
    rs = filter(r -> startswith(r.kind, kind), results)
    isempty(rs) && continue
    found = join(["$v $(count(r -> r.verdict === v, rs))" for v in unique(r.verdict for r in rs)], ", ")
    if all(r -> r.expected === :unknown, rs)
      println(rpad(kind, 26), "found: ", found)
    else
      right = count(r -> r.verdict === r.expected, rs)
      println(rpad(kind, 26), "$right of $(length(rs)) as expected; found: ", found)
    end
  end
  @testset "Jacobians and non-Jacobians of dimension 5" begin
    for r in results
      (r.expected === :unknown || r.stage in (:period_matrix, :setup) && r.verdict === :inconclusive) && continue
      @test r.verdict === r.expected
    end
  end
  return results
end

################################################################################
#
#  Jacobians approaching products: plane quintics acquiring A_{2k} cusps
#
#  A plane quintic with a node at (1, 1) has genus 5. If in the limit t -> 0
#  of F_t = F_0 + t G the curve F_0 acquires singularities of type A_{2k}
#  (y^2 = x^(2k+1) locally: an ordinary cusp for k = 1), the stable limit is
#  the normalization of F_0 (genus 5 - sum k) with a tail of genus k (a
#  hyperelliptic curve, the stable reduction of the singularity) attached at
#  each cusp: a curve of compact type, so the Jacobians of F_t tend to the
#  product of the Jacobians of the components. tails = [1]: 1 + 4, [2]:
#  2 + 3, [1, 1]: 1 + 1 + 3, [1, 2]: 1 + 2 + 2, [1, 1, 1]: 1 + 1 + 1 + 2.
#  Every F_t (t != 0) is an honest curve of genus 5: exact Jacobians, the
#  period matrices from riemann_surface_with_differentials (adjoint conics
#  through the node).
#
################################################################################

# The coefficient of (x - p1)^i (y - p2)^j of the monomials x^a y^b.
_taylor_row(monomials, p, i, j) =
  [a >= i && b >= j ? QQ(binomial(a, i)) * p[1]^(a - i) * QQ(binomial(b, j)) * p[2]^(b - j) : zero(QQ)
   for (a, b) in monomials]

@doc raw"""
    cusp_degeneration_family(tails; coefficients = -5:5) -> NamedTuple

Plane quintics F_t = F_0 + t G with a node at (1, 1) (genus 5 for t != 0)
where F_0 has in addition singularities of type A_{2k} (k in `tails`, 1 or
2, at (0, 0), (-1, 2), (2, -1), each with tangent cone the line y = const):
all coefficients of (x - p1)^i (y - p2)^j of weight 2i + (2k+1)j < 2(2k+1)
vanish, those of y^2 and x^(2k+1) do not. G keeps the node only. The stable
limit is the normalization of F_0 (genus 5 - sum(tails)) with tails of
genera `tails`: J(F_t) tends to a product of Jacobians of dimensions
5 - sum(tails) and tails. Returns (F0, G, numerators (the adjoint conics
through the node: holomorphic differentials numerator dx/F_y), tails,
singular_points).
"""
function cusp_degeneration_family(tails::Vector{Int}; coefficients = -5:5, max_tries::Int = 100)
  @req all(k -> k in (1, 2), tails) && length(tails) <= 3 && sum(tails) <= 4 "tails: at most 3 entries 1 or 2 with sum at most 4."
  R, (x, y) = polynomial_ring(QQ, [:x, :y]; cached = false)
  monomials = [(a, b) for a in 0:5 for b in 0:5-a]
  node = (QQ(1), QQ(1))
  points = [(QQ(0), QQ(0)), (QQ(-1), QQ(2)), (QQ(2), QQ(-1))][1:length(tails)]
  node_rows = [_taylor_row(monomials, node, 0, 0), _taylor_row(monomials, node, 1, 0),
               _taylor_row(monomials, node, 0, 1)]
  cusp_rows = Vector{QQFieldElem}[]
  for (p, k) in zip(points, tails), i in 0:5, j in 0:5-i
    2*i + (2*k + 1)*j < 2*(2*k + 1) && push!(cusp_rows, _taylor_row(monomials, p, i, j))
  end
  to_poly(v) = sum(QQ(v[l]) * x^a * y^b for (l, (a, b)) in enumerate(monomials))
  basis(rows) = _small_kernel_basis(matrix(QQ, length(rows), length(monomials), reduce(vcat, rows)))
  B0, BG = basis([cusp_rows; node_rows]), basis(node_rows)
  @req nrows(B0) > 0 "No quintics with these singularities."
  function random_combination(B)
    c = [rand(coefficients) for _ in 1:nrows(B)]
    return [sum(c[r] * B[r, l] for r in 1:nrows(B)) for l in 1:ncols(B)]
  end
  numerators = [x - 1, y - 1, x^2 - 1, x*y - 1, y^2 - 1]
  # the genus modulo a prime (several primes: _genus_mod_p gives nothing for
  # bad reduction or without a smooth rational point)
  function genus_mod_p(F)
    p = next_prime(2^20)
    for _ in 1:20
      p = next_prime(p + 1)
      gp = try RSR._genus_mod_p(F, p) catch; nothing end
      gp === nothing || return gp
    end
    return nothing
  end
  reasons = Dict{String, Int}()
  reject(r) = (reasons[r] = get(reasons, r, 0) + 1; nothing)
  for _ in 1:max_tries
    F0, G = to_poly(random_combination(B0)), to_poly(random_combination(BG))
    (total_degree(F0) == 5 && total_degree(G) == 5) || (reject("degree"); continue)
    # nondegenerate cusps: the coefficients of y^2 and x^(2k+1)
    ok = true
    for (p, k) in zip(points, tails)
      c(i, j) = sum(_taylor_row(monomials, p, i, j)[l] * coeff(F0, [a, b]) for (l, (a, b)) in enumerate(monomials))
      (!iszero(c(0, 2)) && !iszero(c(2*k + 1, 0))) || (ok = false)
    end
    ok || (reject("degenerate cusp"); continue)
    # genus 5 for t != 0 (one test value) and 5 - sum(tails) for F0
    gt = genus_mod_p(F0 + QQ(1, 7) * G)
    gt == 5 || (reject("genus of F_t: $gt"); continue)
    g0 = genus_mod_p(F0)
    g0 == 5 - sum(tails) || (reject("genus of F_0: $g0"); continue)
    return (F0 = F0, G = G, numerators = numerators, tails = tails, singular_points = points)
  end
  error("No suitable family found in $max_tries tries; rejected: $reasons.")
end

@doc raw"""
    approach_cusp_limit(tails, exponents; prec = 1000, coefficients = -5:5, seed = 1, family = nothing,
                        sign_data = nothing, verbose = true) -> NamedTuple

For t = 2^-k, k in `exponents`, the Jacobians of F_t = F_0 + t G of
cusp_degeneration_family(tails) (or `family`), which tend to a product of
Jacobians of dimensions 5 - sum(tails) and tails: the period matrix (to the
precision it is known), the theta constants (acb_theta_all, Siegel
reduced), the smallest even theta constants relative to the largest (the
ones tending to 0 at the product), and classify_jacobian (allow_vanishing)
with its evidence. Returns (family, results).
"""
function approach_cusp_limit(tails::Vector{Int}, exponents; prec::Int = 1000, coefficients = -5:5, seed::Int = 1,
                             family = nothing, sign_data = nothing, verbose::Bool = true)
  Random.seed!(seed)
  fam = family === nothing ? cusp_degeneration_family(tails; coefficients = coefficients) : family
  verbose && println("F0 = ", fam.F0, "\nG = ", fam.G)
  data4 = _loaded_sign_data(sign_data, 4)
  results = NamedTuple[]
  for k in exponents
    clock = time()
    record = try
      F = fam.F0 + QQ(1, BigInt(2)^k) * fam.G
      RS = riemann_surface_with_differentials(F, fam.numerators, prec)
      tau = Hecke.siegel_reduction(_small_period_matrix(RSR.big_period_matrix(RS)))[2]
      bits = -maximum(RSR._log2_relative_radius(tau[i, j]) for i in 1:5 for j in 1:5)
      t_period = time() - clock
      thetas = Hecke.thetas([zero(base_ring(tau)) for _ in 1:5], tau)
      evens = [v for (c, v) in thetas if RSR._is_even(c)]
      largest = maximum(RSR._safe_log2(RSR._abs64(v)) for v in evens)
      sizes = sort([RSR._safe_log2(RSR._abs64(v)) - largest for v in evens])
      c = classify_jacobian(5, thetas; sign_data = data4, allow_vanishing = true)
      (k = k, status = :ok, period_bits = round(bits, digits = 1), time_period = round(t_period, digits = 1),
       smallest_thetas_log2 = round.(sizes[1:12], digits = 1),
       below_minus_32 = count(<(-32), sizes), verdict = c.verdict, stage = c.stage, classification = c, tau = tau)
    catch err
      err isa InterruptException && rethrow()
      (k = k, status = :error, error = sprint(showerror, err))
    end
    push!(results, record)
    if verbose
      if record.status === :error
        println("t = 2^-$k: error ", first(record.error, 300))
      else
        println("t = 2^-$k: period matrix to $(record.period_bits) bits ($(record.time_period) s), ",
                "$(record.below_minus_32) even thetas below 2^-32, smallest 2^", record.smallest_thetas_log2,
                "; $(record.verdict) ($(record.stage)), ", round(time() - clock, digits = 1), " s")
        println("    ", _evidence_line(record.classification))
      end
    end
  end
  return (family = fam, results = results)
end

@doc raw"""
    degeneration_table(r) -> Vector{NamedTuple}

For the result r of approach_cusp_limit or approach_point (e.g.
approach_hyperelliptic_locus): per t the log2 of the
smallest even theta constant (relative), the smallest singular value of the
squares, the 2nd, 3rd and 4th (the largest of the vanishing ones) singular
values of the quadric relation matrix and the Prym Fay residual, and the slopes of these between consecutive t
against -log2 t (so a quantity ~ t^a has slope -a; with t = s^d, d the order
of the base change, a quantity ~ s^b has slope -b/d). Printed as a table.
"""
function degeneration_table(r)
  rows = NamedTuple[]
  for x in r.results
    # approach_cusp_limit (status :ok, k, classification) or approach_point
    # (status :converged, t, evidence)
    x.status in (:ok, :converged) || continue
    e = hasproperty(x, :classification) ? x.classification.evidence :
        hasproperty(x, :evidence) ? x.evidence : nothing
    e === nothing && continue
    isempty(x.smallest_thetas_log2) && continue
    get_or(key, f) = haskey(e, key) ? f(e[key]) : NaN
    push!(rows, (log2_t = hasproperty(x, :k) ? -Float64(x.k) : log2(Float64(x.t)), theta = x.smallest_thetas_log2[1],
                 squares = get_or(:squares_singular_values_log2, minimum),
                 quadric2 = get_or(:quadric_singular_values_log2, v -> v[2]),
                 quadric3 = get_or(:quadric_singular_values_log2, v -> v[3]),
                 quadric4 = get_or(:quadric_singular_values_log2, v -> length(v) >= 4 ? v[4] : NaN),
                 prym_fay = get_or(:prym_gradient_residual, Float64), stage = x.stage))
  end
  fmt(v) = lpad(isnan(v) ? "-" : string(round(v, digits = 1)), 9)
  println(rpad("log2 t", 9), lpad("theta", 9), lpad("squares", 9), lpad("quad 2", 9), lpad("quad 3", 9),
          lpad("quad 4", 9), lpad("PrymFay", 9), "   slopes (theta, squares, quad 2, quad 3, quad 4)")
  for (i, x) in enumerate(rows)
    line = fmt(x.log2_t) * fmt(x.theta) * fmt(x.squares) * fmt(x.quadric2) * fmt(x.quadric3) * fmt(x.quadric4) *
           fmt(x.prym_fay)
    if i > 1
      p = rows[i - 1]
      dt = x.log2_t - p.log2_t
      slope(a, b) = round((a - b) / dt, digits = 3)
      line *= "   " * join([slope(x.theta, p.theta), slope(x.squares, p.squares), slope(x.quadric2, p.quadric2),
                              slope(x.quadric3, p.quadric3), slope(x.quadric4, p.quadric4)], ", ")
    end
    println(line, "   (", x.stage, ")")
  end
  return rows
end

